#!/usr/bin/env python3
"""Rasterize the approved SVG into a monochrome C mask for Pongo.

Requires rsvg-convert and ImageMagick (magick). Uses the SVG alpha channel;
foreground color is supplied by the framebuffer renderer, not baked into bits.
"""
import argparse
from pathlib import Path
import subprocess

SIZE = 600
HERE = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--size', type=int, default=SIZE)
    args = parser.parse_args()
    global_size = args.size
    if global_size <= 0 or global_size > 2048 or global_size % 8:
        parser.error('--size must be a positive multiple of 8, at most 2048')
    png = subprocess.run(['rsvg-convert', '-w', str(global_size), '-h', str(global_size),
                          str(HERE / 'artwork/omarchy-logo.svg')],
                         check=True, capture_output=True).stdout
    alpha = subprocess.run(['magick', 'png:-', '-alpha', 'extract', '-depth', '8',
                            'gray:-'], input=png, check=True, capture_output=True).stdout
    if len(alpha) != global_size * global_size:
        raise ValueError('Unexpected raster dimensions')
    # Quantize tiny SVG subpixel offsets (.004 units) to a crisp binary mask.
    mask = bytearray(global_size * global_size // 8)
    for i, value in enumerate(alpha):
        if value >= 128:
            mask[i // 8] |= 1 << (7 - i % 8)
    lines = ['/* Generated by boot/pongo/generate-logo.py; do not edit. */',
             '#pragma once', '#include <stdint.h>',
             f'#define OMARCHY_LOGO_SIZE {global_size}u',
             'static const uint8_t omarchy_logo_mask[] = {']
    lines += ['    ' + ', '.join(f'0x{b:02x}' for b in mask[i:i + 16]) + ','
              for i in range(0, len(mask), 16)]
    lines += ['};', '']
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines))
    print(f'{args.output}: {global_size}x{global_size}, {len(mask)} mask bytes')


if __name__ == '__main__':
    main()
